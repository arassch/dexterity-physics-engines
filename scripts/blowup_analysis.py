"""T25 step 1 (no GPU): do joint velocities sit at the velocity limit (a solver clamp) in PhysX but not in Newton?
Do finger torques saturate at the effort limit?

Sources, compared by joint *name*:
  - T18 signal (c) (open-loop replay of the PhysX policy's targets, no cube): ~/runs/step_response/{physx,newton}.npz,
    using only steps before each env's first reset. Has joint_vel but no torques.
  - T17 traces of the PhysX Reorient policy in PhysX and in Newton: ~/runs/traces/reorient_physx_in_{physx,newton}.npz,
    using only steps up to and including each env's first episode end (the step where abnormal_robot fires is kept:
    the snapshot is taken before the reset). Has joint_vel, applied_torque and computed_torque.
Effort limits come from the robot config (isaaclab_assets/robots/kuka_allegro.py: arm 300 N·m, fingers 0.5 N·m); the
traces don't store them. `applied_torque` is Isaac Lab's clipped estimate for an implicit actuator, not a value read
back from the engine.

Per source, engine and joint: max and p99 of |v|/limit, fraction of samples with |v|/limit in [0.98, 1.02], fraction
above 1.02, and (traces only) fraction of samples with |applied_torque| >= 0.99 * effort limit.
Writes results/blowup_step1.md and results/plots/vel_limit_<joint>.png (3 worst finger joints in Newton, signal c).

Run: scripts/run_isaac.sh blowup_analysis blowup_analysis.py
"""

import argparse
import os

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
H = os.path.expanduser("~/runs")
p = argparse.ArgumentParser()
p.add_argument("--sr", default=os.path.join(H, "step_response"))
p.add_argument("--traces", default=os.path.join(H, "traces"))
p.add_argument("--md", default=os.path.join(REPO, "results", "blowup_step1.md"))
p.add_argument("--plots", default=os.path.join(REPO, "results", "plots"))
args = p.parse_args()


def effort_limit(name):
    return 300.0 if name.startswith("iiwa7") else 0.5


def reorder(d, ref):
    names = list(d["joint_names"])
    perm = [names.index(nm) for nm in ref]
    return perm


def stats(v, lim, valid, tau=None, elim=None):
    """v: (T, E, J) in ref order, lim: (E, J), valid: (T, E) bool. Returns dict of (J,) arrays."""
    r = np.abs(v) / lim[None]
    out = {"max": [], "p99": [], "at": [], "over": [], "sat": [], "n": int(valid.sum())}
    for j in range(v.shape[-1]):
        x = r[..., j][valid]
        out["max"].append(x.max())
        out["p99"].append(np.percentile(x, 99))
        out["at"].append(((x >= 0.98) & (x <= 1.02)).mean())
        out["over"].append((x > 1.02).mean())
        if tau is not None:
            out["sat"].append((np.abs(tau[..., j][valid]) >= 0.99 * elim[j]).mean())
    return {k: (np.array(v) if isinstance(v, list) and v else v) for k, v in out.items()}


def load_sr(path, ref):
    d = np.load(path)
    perm = reorder(d, ref)
    v = d["c_joint_vel"][..., perm]
    lim = d["joint_vel_limits"][..., perm]
    valid = d["c_reset"] == 0
    return v, lim, valid


def load_trace(path, ref):
    d = np.load(path)
    perm = reorder(d, ref)
    v = d["joint_vel"][..., perm]
    tau = d["applied_torque"][..., perm]
    lim = d["joint_vel_limits"][..., perm]
    T, E = v.shape[:2]
    fd = d["first_done_step"]
    end = np.where(fd < 0, T - 1, fd)
    valid = np.arange(T)[:, None] <= end[None]
    return v, tau, lim, valid, fd, d


ref = list(np.load(os.path.join(args.sr, "physx.npz"))["joint_names"])
elim = np.array([effort_limit(n) for n in ref])
finger = np.array([not n.startswith("iiwa7") for n in ref])
res = {}
sr = {}
for eng in ("physx", "newton"):
    v, lim, valid = load_sr(os.path.join(args.sr, f"{eng}.npz"), ref)
    sr[eng] = (v, lim, valid)
    res[("T18 signal c", eng)] = stats(v, lim, valid)
    v, tau, lim, valid, fd, _ = load_trace(os.path.join(args.traces, f"reorient_physx_in_{eng}.npz"), ref)
    res[("T17 trace", eng)] = stats(v, lim, valid, tau, elim)

lines = ["# T25 step 1: joint velocity vs velocity limit, effort saturation", "",
         "Generated by `scripts/blowup_analysis.py`. PhysX Reorient policy targets. Ratios are |joint_vel| / joint_vel_limit, "
         "sampled once per control step (not per physics substep). `abnormal_robot` fires above 2.0.", ""]
lims = sr["physx"][1][0]
lines.append(f"Velocity limits read from robot.data (PhysX): arm {np.unique(lims[~finger].round(3))}, "
             f"fingers {np.unique(lims[finger].round(3))} rad/s. Newton: arm "
             f"{np.unique(sr['newton'][1][0][~finger].round(3))}, fingers {np.unique(sr['newton'][1][0][finger].round(3))}.")
lines.append("")
lines.append("## Summary over finger joints (16) and arm joints (7)")
lines.append("")
lines.append("| source | engine | valid samples | finger max | finger p99 (worst joint) | finger frac in [0.98,1.02] | "
             "finger frac > 1.02 | arm max | finger frac at effort limit |")
lines.append("|---|---|---|---|---|---|---|---|---|")
for (src, eng), s in res.items():
    sat = f"{s['sat'][finger].mean():.3f}" if len(s["sat"]) else "n/a (no torques)"
    lines.append(f"| {src} | {eng} | {s['n']} | {s['max'][finger].max():.2f} | {s['p99'][finger].max():.2f} | "
                 f"{s['at'][finger].mean():.4f} | {s['over'][finger].mean():.4f} | {s['max'][~finger].max():.2f} | {sat} |")
lines.append("")
for src in ("T18 signal c", "T17 trace"):
    lines.append(f"## Per joint: {src}")
    lines.append("")
    has_t = len(res[(src, "physx")]["sat"]) > 0
    hdr = "| joint | PhysX max | Newton max | PhysX p99 | Newton p99 | PhysX at-limit | Newton at-limit | PhysX >1.02 | Newton >1.02 |"
    sep = "|---|---|---|---|---|---|---|---|---|"
    if has_t:
        hdr += " PhysX effort-sat | Newton effort-sat |"
        sep += "---|---|"
    lines += [hdr, sep]
    P, N = res[(src, "physx")], res[(src, "newton")]
    for j, nm in enumerate(ref):
        row = (f"| {nm} | {P['max'][j]:.2f} | {N['max'][j]:.2f} | {P['p99'][j]:.2f} | {N['p99'][j]:.2f} | "
               f"{P['at'][j]:.3f} | {N['at'][j]:.3f} | {P['over'][j]:.3f} | {N['over'][j]:.3f} |")
        if has_t:
            row += f" {P['sat'][j]:.3f} | {N['sat'][j]:.3f} |"
        lines.append(row)
    lines.append("")

# plots: 3 worst finger joints in Newton by max ratio on signal c
os.makedirs(args.plots, exist_ok=True)
try:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    Nmax = res[("T18 signal c", "newton")]["max"].copy()
    Nmax[~finger] = -1
    worst = np.argsort(-Nmax)[:3]
    v_dt = float(np.load(os.path.join(args.sr, "physx.npz"))["step_dt"])
    for j in worst:
        fig, ax = plt.subplots(figsize=(7, 3.5))
        for eng, col in (("physx", "tab:blue"), ("newton", "tab:orange")):
            v, lim, valid = sr[eng]
            r = np.abs(v[..., j]) / lim[None, :, j]
            r = np.where(valid, r, np.nan)
            t = np.arange(r.shape[0]) * v_dt
            ax.plot(t, r, color=col, alpha=0.15, lw=0.7)
            ax.plot(t, np.nanmax(r, axis=1), color=col, lw=1.8, label=f"{eng} (max over envs)")
        ax.axhline(1.0, color="k", ls="--", lw=0.8, label="velocity limit")
        ax.axhline(2.0, color="r", ls=":", lw=0.8, label="abnormal_robot (2x)")
        ax.set_xlabel("time (s)")
        ax.set_ylabel("|v| / limit")
        ax.set_title(f"T18 signal c, {ref[j]} (no cube; envs drop out at reset)")
        ax.legend(fontsize=7)
        fig.tight_layout()
        out = os.path.join(args.plots, f"vel_limit_{ref[j]}.png")
        fig.savefig(out, dpi=110)
        plt.close(fig)
        print(f"[T25] wrote {out}")
        lines.append(f"Plot: `results/plots/vel_limit_{ref[j]}.png`")
except ImportError as e:
    lines.append(f"(plots skipped: {e})")

os.makedirs(os.path.dirname(args.md), exist_ok=True)
with open(args.md, "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines[:16]))
print(f"[T25] wrote {args.md}")
