"""T25b: reset counts per setting, and test 2 (are the Newton blow-ups at a joint position limit?).

Reads the signal-(c) .npz files written by scripts/step_response.py (with the T25b recording: c_pre_joint_pos/vel =
joint state when terminations are computed, i.e. the state that tripped abnormal_robot, before the auto-reset;
c_sub_joint_pos/vel = state before every sim.step call). Joints are compared by name.

Usage: python t25b_analysis.py --dir ~/runs/step_response --out results/t25b_tests.md
"""

import argparse
import os

import numpy as np

NEAR = 0.02  # rad

p = argparse.ArgumentParser()
p.add_argument("--dir", default=os.path.expanduser("~/runs/step_response"))
p.add_argument("--out", required=True)
args = p.parse_args()

RUNS = [  # (file stem, test, setting)
    ("t25b_base_physx", "baseline", "PhysX, defaults"),
    ("t25b_base_newton", "baseline", "Newton, defaults (2 substeps)"),
    ("t25b_noself_physx", "1 self-collision", "PhysX, self-collision off"),
    ("t25b_noself_newton", "1 self-collision", "Newton, self-collision off"),
    ("t25b_sub4_newton", "3 time step", "Newton, 4 substeps"),
    ("t25b_sub4clamp_newton", "3 time step", "Newton, 4 substeps + vel clamp"),
    ("t25b_sub8_newton", "3 time step", "Newton, 8 substeps"),
    ("t25b_sub8clamp_newton", "3 time step", "Newton, 8 substeps + vel clamp"),
]


def load(stem):
    f = os.path.join(args.dir, stem + ".npz")
    return np.load(f, allow_pickle=False) if os.path.exists(f) else None


def first_resets(d):
    r = d["c_reset"]  # (T, n), cumulative
    hit = np.where(r[-1] > 0)[0]
    first = np.argmax(r > 0, axis=0)
    ab = [e for e in hit if d["c_term_abnormal_robot"][first[e], e] > 0]
    return hit, first, ab


lines = ["# T25b: where does the one-substep kick come from?", "",
         "Signal (c), 64 envs, 120 control steps, `--adr max`, no cube (`scripts/step_response.py`). "
         "Generated by `scripts/t25b_analysis.py`.", "",
         "## Resets out of 64", "",
         "| test | setting | envs reset | abnormal_robot | first-reset steps (abnormal) |", "|---|---|---|---|---|"]
data = {}
for stem, test, setting in RUNS:
    d = load(stem)
    if d is None:
        lines.append(f"| {test} | {setting} | not run | | |")
        continue
    data[stem] = d
    hit, first, ab = first_resets(d)
    st = sorted(int(first[e]) for e in ab)
    rng = f"{st[0]}–{st[-1]}" if st else "–"
    lines.append(f"| {test} | {setting} | {len(hit)} | {len(ab)} | {rng} |")

# ---- test 2
lines += ["", "## Test 2: joint position limits at the Newton blow-ups", ""]
nw, px = data.get("t25b_base_newton"), data.get("t25b_base_physx")
if nw is None or px is None:
    lines.append("baseline runs missing")
else:
    names_n = list(nw["joint_names"])
    names_p = list(px["joint_names"])
    perm = [names_p.index(nm) for nm in names_n]  # physx array in newton's joint order
    vlim = nw["joint_vel_limits"][0]
    hard = nw["joint_pos_limits"][0]
    soft = nw["soft_joint_pos_limits"][0]
    finger = np.array([not nm.startswith("iiwa7") for nm in names_n])

    def near(q, lim):  # (..., nj) -> bool, within NEAR of lower or upper
        return (np.abs(q - lim[:, 0]) < NEAR) | (np.abs(q - lim[:, 1]) < NEAR)

    hit, first, ab = first_resets(nw)
    rows = []
    n_cul_near_hard = n_cul_near_soft = n_any_near_hard = n_prev_near = 0
    for e in ab:
        f = first[e]
        q, v = nw["c_pre_joint_pos"][f, e], nw["c_pre_joint_vel"][f, e]
        cul = np.where(np.abs(v) > 2 * vlim)[0]  # joints that tripped the 2x check
        if len(cul) == 0:
            cul = np.array([int(np.argmax(np.abs(v) / vlim))])
        nh, ns = near(q, hard), near(q, soft)
        # state before the last physics step of this control step (just before the kick)
        sub = nw["c_sub_joint_pos"]
        k = min(2 * f + 1, sub.shape[0] - 1)
        q_prev, v_prev = sub[k, e], nw["c_sub_joint_vel"][k, e]
        nprev = near(q_prev, hard) | near(q_prev, soft)
        n_cul_near_hard += bool(nh[cul].any())
        n_cul_near_soft += bool(ns[cul].any())
        n_any_near_hard += bool((nh | ns)[finger].any())
        n_prev_near += bool(nprev[cul].any())
        qp, vp = px["c_pre_joint_pos"][f, e][perm], px["c_pre_joint_vel"][f, e][perm]
        rows.append((e, f, cul, q, v, q_prev, v_prev, qp, vp, nh, ns))

    N = len(ab)
    lines += [f"Newton baseline: {N} `abnormal_robot` envs. \"Culprit\" = joint with |v| > 2× its limit at the reset "
              f"step. Near = within {NEAR} rad of the hard (`joint_pos_limits`) or soft (`soft_joint_pos_limits`) "
              "limit. PhysX column: same env, same control step, same joint (by name).", "",
              "| count (of blow-ups) | Newton |", "|---|---|",
              f"| a culprit joint near its **hard** limit at the reset step | {n_cul_near_hard}/{N} |",
              f"| a culprit joint near its **soft** limit at the reset step | {n_cul_near_soft}/{N} |",
              f"| a culprit joint near a limit one physics step earlier | {n_prev_near}/{N} |",
              f"| any finger joint near a limit at the reset step | {n_any_near_hard}/{N} |", ""]

    # base rate: over all valid env-steps (before any reset), fraction of finger joint-samples near a limit
    def base_rate(d, order=None):
        q = d["c_pre_joint_pos"]
        valid = d["c_reset"] == 0
        if order is not None:
            q = q[..., order]
        nl = near(q, hard) | near(q, soft)
        return nl[valid][:, finger].mean(), nl[valid][:, finger].any(-1).mean()

    bn, bn_any = base_rate(nw)
    bp, bp_any = base_rate(px, perm)
    lines += ["Base rate over all env-steps before any reset (finger joints):", "",
              "| engine | joint-samples near a limit | env-steps with any finger joint near a limit |", "|---|---|---|",
              f"| Newton | {bn:.3f} | {bn_any:.3f} |",
              f"| PhysX | {bp:.3f} | {bp_any:.3f} |", ""]

    lines += ["Per blow-up (culprit joints only; q relative to the nearer hard limit, v / velocity limit):", "",
              "| env | step | joint | Newton q−lim (step before) | Newton q−lim (reset) | Newton v/vlim (before → reset) "
              "| PhysX q−lim | PhysX v/vlim |", "|---|---|---|---|---|---|---|---|"]

    def dlim(q, j):
        lo, hi = hard[j]
        return q - lo if abs(q - lo) < abs(q - hi) else q - hi

    for e, f, cul, q, v, q_prev, v_prev, qp, vp, nh, ns in rows:
        for j in cul:
            lines.append(f"| {e} | {f} | {names_n[j]} | {dlim(q_prev[j], j):+.3f} | {dlim(q[j], j):+.3f} | "
                         f"{v_prev[j] / vlim[j]:+.2f} → {v[j] / vlim[j]:+.2f} | {dlim(qp[j], j):+.3f} | "
                         f"{vp[j] / vlim[j]:+.2f} |")
    # which joints
    from collections import Counter

    c = Counter(names_n[j] for r in rows for j in r[2])
    lines += ["", "Culprit joints: " + ", ".join(f"`{k}` ×{v}" for k, v in c.most_common()), ""]
    for key in ("newton_joint_limit_ke", "newton_joint_limit_kd"):
        if key in nw:
            lines.append(f"- `{key}` (Newton model, all joints incl. cube): unique values {np.unique(nw[key]).tolist()}")

os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
with open(args.out, "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("\n".join(lines))
