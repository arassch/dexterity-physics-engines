"""Compare T18 step responses between engines, by joint name. Writes results/step_response.md and
results/plots/step_<joint>.png (the 6 joints with the largest PhysX-vs-Newton difference on signal a).

Usage: scripts/run_isaac.sh analyze_step_response analyze_step_response.py \
           [--physx ~/runs/step_response/physx.npz] [--newton ~/runs/step_response/newton.npz]
Metrics on signal (a), per stepped joint, averaged over the envs that stepped that joint and did not reset:
  rise time 10-90 % (s), overshoot (% of the step), steady-state error (mean |q - target| over the last 10 steps, rad).
RMS difference between engines: sqrt(mean over steps and valid envs of (q_physx - q_newton)^2), per joint, for a-c.
"""

import argparse
import os

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = argparse.ArgumentParser()
p.add_argument("--physx", default=os.path.expanduser("~/runs/step_response/physx.npz"))
p.add_argument("--newton", default=os.path.expanduser("~/runs/step_response/newton.npz"))
p.add_argument("--md", default=os.path.join(REPO, "results", "step_response.md"))
p.add_argument("--plots", default=os.path.join(REPO, "results", "plots"))
args = p.parse_args()


def load(path, ref_names=None):
    d = dict(np.load(path, allow_pickle=False))
    names = list(d["joint_names"])
    if ref_names is None:
        return d, names
    perm = [names.index(nm) for nm in ref_names]  # reorder this engine's joints to the reference order
    for k, v in list(d.items()):
        if k.endswith(("_joint_pos", "_joint_vel", "_target")):
            d[k] = v[..., perm]
        elif k in ("default_joint_pos", "joint_vel_limits", "joint_stiffness", "joint_damping", "joint_armature",
                   "joint_friction_coeff"):
            d[k] = v[..., perm]
        elif k == "soft_joint_pos_limits":
            d[k] = v[:, perm]
    inv = {i: ref_names.index(nm) for i, nm in enumerate(names)}
    d["a_joint"] = np.array([inv[int(j)] for j in d["a_joint"]])
    d["joint_names"] = np.array(ref_names)
    return d, ref_names


P, names = load(args.physx)
N, _ = load(args.newton, names)
dt = float(P["step_dt"])
T = P["a_joint_pos"].shape[0]
nj = len(names)
# Signal (a) steps joint (env % 23) in each engine's *own* order, so the env -> joint map differs by name between
# engines; (a) is therefore compared per named joint on the mean over the envs that stepped it. (b) is identical in
# every env, and (c) picks trace envs by env index, so (b) and (c) are compared env by env.
for j in range(nj):
    for d, eng in ((P, "PhysX"), (N, "Newton")):
        assert (d["a_joint"] == j).any(), f"{eng}: no env stepped {names[j]}"


def step_metrics(d, j):
    envs = np.where((d["a_joint"] == j) & (d["a_reset"][-1] == 0))[0]
    if len(envs) == 0:
        return None
    q = d["a_joint_pos"][:, envs, j]
    q0 = d["default_joint_pos"][envs, j]
    tgt = d["a_target"][-1, envs, j]
    step = tgt - q0
    x = (q - q0) / step  # normalised response, 1 = at target
    xm = x.mean(axis=1)
    t = (np.arange(T) + 1) * dt

    def first(th):
        idx = np.where(xm >= th)[0]
        return t[idx[0]] if len(idx) else np.nan

    rise = first(0.9) - first(0.1)
    over = max(0.0, xm.max() - 1.0) * 100
    sse = np.abs(q[-10:] - tgt).mean()
    return rise, over, sse, xm


def rms(sig, j=None):
    if sig == "a":  # stepped joint, mean trajectory over the valid envs that stepped it, per engine
        out = np.full(nj, np.nan)
        for jj in range(nj):
            mp = (P["a_joint"] == jj) & (P["a_reset"][-1] == 0)
            mn = (N["a_joint"] == jj) & (N["a_reset"][-1] == 0)
            if mp.any() and mn.any():
                d = P["a_joint_pos"][:, mp, jj].mean(1) - N["a_joint_pos"][:, mn, jj].mean(1)
                out[jj] = np.sqrt((d**2).mean())
        return out
    valid = (P[f"{sig}_reset"] == 0) & (N[f"{sig}_reset"] == 0)  # (T, envs)
    diff = P[f"{sig}_joint_pos"] - N[f"{sig}_joint_pos"]
    return np.array([np.sqrt((diff[..., jj][valid] ** 2).mean()) if valid.any() else np.nan for jj in range(nj)])


rows, curves = [], {}
for j in range(nj):
    mp, mn = step_metrics(P, j), step_metrics(N, j)
    rows.append((j, mp, mn))
    curves[j] = (mp[3] if mp else None, mn[3] if mn else None)
ra, rb, rc = rms("a"), rms("b"), rms("c")


def f(x, fmt):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else format(x, fmt)


lines = [
    "# T18 · Robot-only step response, PhysX vs Newton (no policy, no cube)",
    "",
    "Generated by `scripts/analyze_step_response.py` from `~/runs/step_response/{physx,newton}.npz` "
    "(`scripts/step_response.py`). Reorient Play env, `presets=cube`, ADR difficulty 0, robot startup randomisation "
    f"(gains, joint friction, material) off, cube parked out of reach. {P['a_joint_pos'].shape[1]} envs, {T} control "
    f"steps of {dt:.4f} s per signal. Joints compared **by name**.",
    "",
    "Signals: (a) +0.3 rad step on one joint per env (−0.3 if + leaves the soft limits); (b) 1 Hz, 0.2 rad sine on all "
    "16 finger joints; (c) T17 physx→physx policy targets replayed open-loop as offsets from the default pose.",
    "",
    f"Envs that reset during a signal (excluded): PhysX a/b/c = {int(P['a_reset'][-1].sum())}/"
    f"{int(P['b_reset'][-1].sum())}/{int(P['c_reset'][-1].sum())}, Newton = {int(N['a_reset'][-1].sum())}/"
    f"{int(N['b_reset'][-1].sum())}/{int(N['c_reset'][-1].sum())}.",
    "",
    *[
        f"{eng} signal {s}: first reset at control step min {int(fr.min())}, median {int(np.median(fr))}, max "
        f"{int(fr.max())} (of {T}). The termination term was not recorded per env; time_out (300 steps) cannot fire "
        "within 120 steps and the cube is parked, so these are almost certainly `abnormal_robot`."
        for eng, d in (("PhysX", P), ("Newton", N))
        for s in "abc"
        for fr in [np.argmax(d[f"{s}_reset"] > 0, axis=0)[d[f"{s}_reset"][-1] > 0]]
        if len(fr)
    ],
    "",
    "| Joint | Rise PhysX (s) | Rise Newton (s) | Overshoot PhysX (%) | Overshoot Newton (%) | SSE PhysX (rad) | "
    "SSE Newton (rad) | RMS diff a (rad) | RMS diff b (rad) | RMS diff c (rad) |",
    "|---|---|---|---|---|---|---|---|---|---|",
]
for j, mp, mn in rows:
    lines.append(
        f"| {names[j]} | {f(mp and mp[0], '.3f')} | {f(mn and mn[0], '.3f')} | {f(mp and mp[1], '.1f')} | "
        f"{f(mn and mn[1], '.1f')} | {f(mp and mp[2], '.4f')} | {f(mn and mn[2], '.4f')} | {f(ra[j], '.4f')} | "
        f"{f(rb[j], '.4f')} | {f(rc[j], '.4f')} |"
    )
lines += [
    "",
    f"Mean RMS difference over joints: a {np.nanmean(ra):.4f} rad, b {np.nanmean(rb):.4f} rad (finger joints: "
    f"{np.nanmean(rb[[not n.startswith('iiwa7') for n in names]]):.4f}), c {np.nanmean(rc):.4f} rad.",
]
for key in ("joint_stiffness", "joint_damping", "joint_armature", "joint_friction_coeff"):
    if key in P and key in N:
        lines += ["", f"`{key}` (env 0) PhysX vs Newton:", "",
                  "| Joint | PhysX | Newton |", "|---|---|---|"]
        lines += [f"| {names[j]} | {P[key][0, j]:.4g} | {N[key][0, j]:.4g} |" for j in range(nj)]

top = [int(j) for j in np.argsort(-np.nan_to_num(ra, nan=-1))[:6]]
lines += ["", "Plots (6 joints with the largest RMS difference on signal a): "
          + ", ".join(f"`results/plots/step_{names[j]}.png`" for j in top)]
os.makedirs(os.path.dirname(args.md), exist_ok=True)
with open(args.md, "w") as fh:
    fh.write("\n".join(lines) + "\n")
print(f"[ANALYZE] wrote {args.md}")

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

os.makedirs(args.plots, exist_ok=True)
t = (np.arange(T) + 1) * dt
for j in top:
    fig, ax = plt.subplots(figsize=(6, 3.5))
    cp, cn = curves[j]
    if cp is not None:
        ax.plot(t, cp, label="PhysX", color="#1f77b4")
    if cn is not None:
        ax.plot(t, cn, label="Newton", color="#d62728")
    ax.axhline(1.0, color="0.6", lw=0.8, ls="--")
    ax.set_xlabel("time (s)")
    ax.set_ylabel("normalised position (1 = target)")
    ax.set_title(f"{names[j]}: 0.3 rad step (RMS diff {ra[j]:.3f} rad)")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(os.path.join(args.plots, f"step_{names[j]}.png"), dpi=120)
    plt.close(fig)
print(f"[ANALYZE] plots: {[names[j] for j in top]}")
